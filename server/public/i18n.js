import { html } from '/vendor/preact-htm.js';

const STORE_KEY = 'multicam.lang';

// 瀏覽器的語言：中文（任何地區）用繁體中文，其他一律英文
export function browserLang() {
  for (const tag of navigator.languages?.length ? navigator.languages : [navigator.language]) {
    if (/^zh/i.test(tag)) return 'zh-TW';
    if (/^[a-z]{2,3}(-|$)/i.test(tag)) return 'en';
  }
  return 'en';
}

// 設定是 auto、zh-TW 或 en
export const resolveLang = (setting) => (setting === 'zh-TW' || setting === 'en' ? setting : browserLang());

// 連上伺服器前先用上次的語言，畫面才不會閃一下另一種語言
let lang = (() => {
  try {
    const saved = localStorage.getItem(STORE_KEY);
    if (saved === 'zh-TW' || saved === 'en') return saved;
  } catch {}
  return browserLang();
})();

export const getLang = () => lang;

export function setLang(next) {
  lang = next;
  document.documentElement.lang = next === 'en' ? 'en' : 'zh-Hant-TW';
  document.title = tr('page.title');
  try {
    localStorage.setItem(STORE_KEY, next);
  } catch {}
}

export function tr(key, p = {}) {
  const entry = STRINGS[lang][key] ?? STRINGS['zh-TW'][key];
  if (entry === undefined) return key;
  return typeof entry === 'function' ? entry(p) : entry.replace(/\{(\w+)\}/g, (_, k) => p[k] ?? '');
}

